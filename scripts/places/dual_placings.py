#!/usr/bin/env python3 -I
"""Per-opponent placings for double duals whose full results (all teams) are on disk: 2019 and 2023 Ravenna-Streetsboro (Hy-Tek texts).
For each opponent, every Cloverleaf performance gets a MeetPlacing (MeetParticipantId = that opponent) = its rank among the athletes of the two teams; points from the meet's
scoring template (5-3-1; relays split /4). Also creates the MeetParticipants rows and sets MeetType 2 + the template. usage: dual_placings.py <out.sql>"""
import os, re, sys, collections
H = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, H)
from places_lib import *
MEETS = {327: '../crawl/milesplit-raw/ms-354958.txt', 70: '/tmp/msraw/ms-536722.txt'}
OPPS = {'Ravenna': 84, 'Streetsboro': 93}
def mark(tok):
    tok = tok.strip()
    m = re.match(r'^(?:(\d+):)?(\d+(?:\.\d+)?)[a-z]?$', tok)
    if m and not re.match(r'^\d+-', tok): return 'run', (int(m.group(1)) * 60 if m.group(1) else 0) + float(m.group(2))
    m = re.match(r'^(\d+)-(\d+(?:\.\d+)?)$', tok)
    return ('field', int(m.group(1)) * 12 + float(m.group(2))) if m else (None, None)
def event(t):
    t = t.strip(); g = 2 if re.match(r'^(Girls|Women)', t) else 1 if re.match(r'^(Boys|Men)', t) else None
    t = re.sub(r'^(Girls|Boys|Women|Men)\s+', '', t).strip()
    t = re.sub(r'\s+(Meter|Meters)\b', '', t, flags=re.I)
    if re.match(r'^4x\d+ Relay', t, re.I): return g, re.sub(r' Relay', 'M Relay', t, flags=re.I).replace('4x', '4x', 1)
    m = re.match(r'^(\d+) (?:Dash|Run|Hurdles|dash|run|hurdles)', t, re.I)
    if m: return g, m.group(1) + 'M' + (' Hurdles' if re.search('hurdles', t, re.I) else '')
    m = re.match(r'^(\d+) (?:meter )?(Hurdles|Dash|Run)', t, re.I)
    return g, {'Shot Put': 'Shot Put', 'Discus Throw': 'Discus', 'Discus': 'Discus', 'High Jump': 'High Jump', 'Long Jump': 'Long Jump', 'Pole Vault': 'Pole Vault', 'Triple Jump': 'Triple Jump', 'Javelin Throw': 'Javelin'}.get(t, t)
def school(s):
    s = s.replace("'A'", '').replace("'B'", '').strip()
    return 'Cloverleaf' if re.search(r'cloverleaf', s, re.I) else 'Streetsboro' if re.search(r'streetsboro', s, re.I) else 'Ravenna' if re.search(r'ravenna', s, re.I) else None
def parse(path):
    ev = None; out = collections.defaultdict(list); seen = set()
    for l in open(path, encoding='utf-8', errors='replace').read().split('\n'):
        s = l.strip()
        m = re.match(r'^(Girls|Boys|Women|Men)\s+(\S.*?)\s*$', s)
        if m and not re.search(r'\d+\)|Team|\d{2,}[.:]\d', s): ev = event(s); continue
        if not ev: continue
        r = re.match(r'^\s*(?:\d+|--)\s+(?:(?P<name>[A-Za-z][^\d]*?)\s+(?P<yr>\d{1,2})\s+)?(?P<school>[A-Za-z][A-Za-z.\' &-]*?)\s{2,}(?P<rest>.+)$', l)
        if not r: continue
        sc = school(r.group('school'))
        toks = [t for t in r.group('rest').split() if mark(t)[0]]
        if not sc or not toks: continue
        k, v = mark(toks[-1] if len(toks) > 1 and re.search(r'Seed', l) is None and False else toks[0]) if False else mark(toks[-1] if 'Seed' in ''.join(open(path).read()[:3000]) else toks[0])
        out[ev].append((sc, (r.group('name') or '').strip(), k, v))
    return out
tmpl = {int(p): float(pts) for p, pts in q("SELECT tp.Place, tp.Points FROM ScoringTemplatePlaces tp JOIN ScoringTemplates t ON t.Id=tp.ScoringTemplateId WHERE t.Name LIKE 'Dual Meet%'")}
perfs = collections.defaultdict(list)
for pid, mid, g, en, name, t, d in q("SELECT p.Id, p.MeetId, e.Gender, e.Name, ISNULL(a.FirstName+' '+a.LastName,''), ISNULL(CAST(p.TimeSeconds AS varchar(30)),''), ISNULL(CAST(p.DistanceInches AS varchar(30)),'') FROM Performances p JOIN Events e ON e.Id=p.EventId LEFT JOIN Athletes a ON a.Id=p.AthleteId WHERE p.MeetId IN (327,70) AND p.ResultStatus=0"):
    perfs[(int(mid), int(g), en)].append((int(pid), name, float(t) if t else None, float(d) if d else None))
info = {int(i): (n, d) for i, n, d in q("SELECT Id, Name, CONVERT(varchar(10), Date, 120) FROM Meets WHERE Id IN (327,70)")}
lines = ["-- Generated by scripts/places/dual_placings.py. Double dual per-opponent placings (rank among the two teams; template points; relays split /4). Id-independent; re-runnable.",
         "SET QUOTED_IDENTIFIER ON;", "SET XACT_ABORT ON;", "BEGIN TRANSACTION;", "DECLARE @m INT, @t INT, @pid INT, @mp INT, @ath INT;", "SET @t = (SELECT TOP 1 Id FROM ScoringTemplates WHERE Name LIKE N'Dual Meet%' AND Deleted=0);", ""]
notes = []; n = 0
for mid, path in MEETS.items():
    path = path if path.startswith('/') else os.path.join(H, path)
    mn, md = info[mid]
    lines += [f"-- ===== {mn} =====", f"SET @m = (SELECT TOP 1 Id FROM Meets WHERE Name=N'{esc(mn)}' AND CAST(Date AS date)='{md}');", "IF @m IS NULL THROW 50030, 'meet missing', 1;",
              "UPDATE Meets SET MeetType=2, ScoringTemplateId=@t WHERE Id=@m;"]
    for i, (opp, sid) in enumerate(OPPS.items()):
        lines.append(f"IF NOT EXISTS (SELECT 1 FROM MeetParticipants mp JOIN Schools s ON s.Id=mp.SchoolId WHERE mp.MeetId=@m AND s.Name=N'{opp}' AND mp.Deleted=0) INSERT INTO MeetParticipants (MeetId, SchoolId, Gender, SortOrder) SELECT @m, Id, NULL, {i} FROM Schools WHERE Name=N'{opp}';")
    res = parse(path)
    for (g, en), rows in sorted(res.items(), key=lambda x: str(x[0])):
        if g is None: continue
        us = [r for r in rows if r[0] == 'Cloverleaf']
        if not us: continue
        isr = en.startswith('4x'); isrun = rows[0][2] == 'run'
        cand = perfs.get((mid, g, en), [])
        for opp in OPPS:
            pool = [r for r in rows if r[0] in ('Cloverleaf', opp)]
            order = sorted(pool, key=lambda r: r[3] if isrun else -r[3])
            for u in us:
                better = sum(1 for r in pool if (r[3] < u[3] - 1e-9 if isrun else r[3] > u[3] + 1e-9))
                place = better + 1
                if isr: hit = [c for c in cand if c[2] is not None and abs(c[2] - u[3]) < 0.06]
                else:
                    hit = [c for c in cand if c[1] and norm(c[1]) == norm(re.sub(r'^(.+?),\s*(.+)$', r'\2 \1', u[1]))]
                    if not hit: hit = [c for c in cand if c[1] and fuzzy(norm(re.sub(r'^(.+?),\s*(.+)$', r'\2 \1', u[1])), c)]
                if len(hit) != 1: notes.append(f"{'AMBIG' if hit else 'NO MATCH'} {mn} {en} g{g} {u[1] or u[3]} vs {opp}"); continue
                pts = tmpl.get(place, 0.0); n += 1
                nm = hit[0][1]
                if isr: where = f"AthleteId IS NULL AND e.Gender={g} AND e.Name=N'{en}' AND ABS(p.TimeSeconds-{hit[0][2]})<0.06"
                else: where = f"a.FirstName+N' '+a.LastName=N'{esc(nm)}' AND e.Gender={g} AND e.Name=N'{en}'"
                lines.append(f"SET @pid = (SELECT TOP 1 p.Id FROM Performances p JOIN Events e ON e.Id=p.EventId {'LEFT ' if isr else ''}JOIN Athletes a ON a.Id=p.AthleteId WHERE p.MeetId=@m AND {where});".replace('LEFT JOIN Athletes a ON a.Id=p.AthleteId WHERE p.MeetId=@m AND AthleteId IS NULL', 'WHERE p.MeetId=@m AND p.AthleteId IS NULL'))
                lines.append(f"SET @mp = (SELECT TOP 1 mp.Id FROM MeetParticipants mp JOIN Schools s ON s.Id=mp.SchoolId WHERE mp.MeetId=@m AND s.Name=N'{opp}' AND mp.Deleted=0);")
                full = pts; split = round(pts / 4, 2) if isr else pts
                lines.append(f"IF @pid IS NOT NULL AND @mp IS NOT NULL AND NOT EXISTS (SELECT 1 FROM MeetPlacings WHERE PerformanceId=@pid AND MeetParticipantId=@mp) INSERT INTO MeetPlacings (MeetId, PerformanceId, MeetParticipantId, Place, FullPoints, SplitPoints) VALUES (@m, @pid, @mp, {place}, {full}, {split});")
    lines.append("")
lines += ["COMMIT TRANSACTION;", "", f"-- {n} per-opponent placings"] + [f"-- NOTE: {x}" for x in notes]
open(sys.argv[1], 'w').write('\n'.join(lines) + '\n'); print(n, 'placings;', len(notes), 'unmatched'); [print(' ', x) for x in notes[:25]]

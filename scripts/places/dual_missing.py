#!/usr/bin/env python3 -I
"""Inserts the Cloverleaf individual results of the 2019/2023 Ravenna-Streetsboro double duals that are missing from the DB (from the full Hy-Tek texts). usage: dual_missing.py <out.sql>"""
import os, re, sys, collections
H = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, H)
exec(compile(open(os.path.join(H, 'dual_placings.py')).read().split("tmpl =")[0], 'dp', 'exec'))
from places_lib import q, norm, esc
ALIASES = {'addison evans': 'addie evans', 'tim shores': 'timmy shores'}
info = {int(i): (n, d) for i, n, d in q("SELECT Id, Name, CONVERT(varchar(10), Date, 120) FROM Meets WHERE Id IN (327,70)")}
perfs = collections.defaultdict(list)
for mid, g, en, name in q("SELECT p.MeetId,e.Gender,e.Name,ISNULL(a.FirstName+' '+a.LastName,'') FROM Performances p JOIN Events e ON e.Id=p.EventId LEFT JOIN Athletes a ON a.Id=p.AthleteId WHERE p.MeetId IN (327,70)"): perfs[(int(mid), int(g), en)].append(name)
ath = {}
for i, f, l, g in q("SELECT Id,FirstName,LastName,Gender FROM Athletes"): ath.setdefault((norm(f + ' ' + l), int(g)), []).append(f + ' ' + l)
lines = ["-- Generated by scripts/places/dual_missing.py: Cloverleaf individual results of the 2019/2023 Ravenna-Streetsboro double duals that the DB lacked (Hy-Tek texts). Id-independent; re-runnable.",
         "SET QUOTED_IDENTIFIER ON;", "SET XACT_ABORT ON;", "BEGIN TRANSACTION;", "DECLARE @m INT, @a INT, @e INT;", ""]
n = 0; skipped = []
for mid, path in MEETS.items():
    path = path if path.startswith('/') else os.path.join(H, path)
    mn, md = info[mid]
    lines += [f"-- ===== {mn} =====", f"SET @m = (SELECT TOP 1 Id FROM Meets WHERE Name=N'{esc(mn)}' AND CAST(Date AS date)='{md}');", "IF @m IS NULL THROW 50060, 'meet missing', 1;"]
    seen = set()
    for (g, en), rows in sorted(parse(path).items(), key=lambda x: str(x[0])):
        if g is None or en.startswith('4x'): continue
        for sc, name, k, v in rows:
            if sc != 'Cloverleaf' or v is None: continue
            nm = re.sub(r'^(.+?),\s*(.+)$', r'\2 \1', name).replace('.', '')
            key = ALIASES.get(norm(nm), norm(nm))
            if any(norm(h) == key for h in perfs.get((mid, g, en), [])) or (g, en, key) in seen: continue
            cand = ath.get((key, g))
            if not cand or len(cand) != 1: skipped.append(f"{mn} {en} g{g} {nm}: {'ambiguous' if cand else 'athlete not in DB'}"); continue
            seen.add((g, en, key)); n += 1; who = cand[0]
            col, val = ('DistanceInches', v) if k == 'field' else ('TimeSeconds', v)
            fn, _, ln = who.partition(' ')
            lines.append(f"-- {who} {en} {v}")
            lines.append(f"SET @a = (SELECT TOP 1 Id FROM Athletes WHERE FirstName+N' '+LastName=N'{esc(who)}' AND Gender={g});")
            lines.append(f"SET @e = (SELECT TOP 1 Id FROM Events WHERE Name=N'{en}' AND Gender={g} AND Environment=1);")
            lines.append(f"IF @a IS NOT NULL AND @e IS NOT NULL AND NOT EXISTS (SELECT 1 FROM Performances WHERE AthleteId=@a AND MeetId=@m AND EventId=@e) INSERT INTO Performances (AthleteId, MeetId, EventId, {col}, SchoolRecord, SeasonBest, PersonalBest, ResultStatus) VALUES (@a, @m, @e, {v}, 0, 0, 0, 0);")
lines += ["COMMIT TRANSACTION;", "EXEC sp_RebuildLeaderboards;", "", f"-- {n} results"] + [f"-- NOTE: {x}" for x in skipped]
open(sys.argv[1], 'w').write('\n'.join(lines) + '\n'); print(n, 'results;', len(skipped), 'skipped'); [print(' ', x) for x in skipped]

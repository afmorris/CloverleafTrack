#!/usr/bin/env python3 -I
"""Team results (place, field size, score) for non-dual meets from Hy-Tek texts (/tmp/msraw; ids.txt = '<msMeetId> <dbMeetId>'). Writes Id-independent SQL that fills MeetTeamResults
(MeetId, Gender, OpponentMeetParticipantId NULL, OurScore, Place, FieldSize) only where the meet has no row for that gender. usage: team_results.py <out.sql>"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from places_lib import *
LOCAL = re.compile(r'cloverleaf|lodi', re.I)
def blocks(text):
    """yield (gender, events, [(place, team, score)])"""
    L = text.split('\n'); i = 0
    while i < len(L):
        l = L[i]
        m = re.search(r'\b(Women|Men|Girls?|Boys?)\b[^\n]*Team (?:Ranking|Score)s?[^\n]*?(?:(\d+)\s+Events? Scored)?', l, re.I)
        if m and not re.search(r'\b(MS|Middle|Metro|County)\b', l, re.I) and 'XC' not in l:
            g = 2 if m.group(1).lower().startswith(('w', 'g')) else 1
            ev = int(m.group(2)) if m.group(2) else (int(re.search(r'(\d+)\s*Events?\s*Scored', l).group(1)) if re.search(r'(\d+)\s*Events?\s*Scored', l) else None)
            ent = []; j = i + 1
            while j < len(L) and j < i + 80:
                s = L[j]
                if re.match(r'^\s*=+\s*$', s) or re.match(r'^\s*-+\s*$', s) or re.match(r'^\s*Team\s+Pts', s) or not s.strip(): j += 1; 
                elif re.search(r'\d+\)\s', s): ent += [(int(a), b.strip(), float(c)) for a, b, c in re.findall(r'(\d+)\)\s+([^\d\t]+?)\s+(\d+(?:\.\d+)?)(?=\s|$)', s)]; j += 1
                elif re.match(r'^\s*\d+\s+\S', s) and re.search(r'\s\d+(\.\d+)?\s', s): 
                    mm = re.match(r'^\s*(\d+)\s+(.+?)\s{2,}(\d+(?:\.\d+)?)\b', s)
                    if mm: ent.append((int(mm.group(1)), mm.group(2).strip(), float(mm.group(3))))
                    j += 1
                else: break
            if ent: yield g, ev, ent
            i = j; continue
        i += 1
import glob
names = {n: int(i) for i, n in q("SELECT Id, Name FROM Meets WHERE Name LIKE '%OHSAA%State%'")}
def statemeet(year, div):
    c = [i for n, i in names.items() if n.startswith(f'{year} OHSAA Division {div} State')]
    return c[0] if len(c) == 1 else None
sources = []
for l in open('/tmp/msraw/ids.txt'):
    p = l.split()
    if len(p) >= 2 and os.path.exists(f'/tmp/msraw/ms-{p[0]}.txt'): sources.append((f'/tmp/msraw/ms-{p[0]}.txt', int(p[1]), 'ms ' + p[0]))
for f in glob.glob('/tmp/ohsaa/pages/*.txt'):
    b = os.path.basename(f)[:-4]
    if re.search(r'MeetProg|heat|part', b) or b.endswith('4'): continue
    m = statemeet(b[:4], {'1': 'I', '2': 'II', '3': 'III'}.get(b[-1], '?'))
    if m: sources.append((f, m, 'state ' + b))
for f in glob.glob('/tmp/ohsaa_old/p20*-*.txt'):
    m = re.match(r'.*/p(\d{4})-(?:b|g)d(\d)reslt', f); mm = statemeet(m.group(1), {'1': 'I', '2': 'II', '3': 'III'}[m.group(2)]) if m else None
    if mm: sources.append((f, mm, 'state-old ' + os.path.basename(f)))
rows = []
for path, dbid, tag in sources:
    p = [None, str(dbid)]
    seen = set()
    for g, ev, ent in blocks(open(path, encoding='utf-8', errors='replace').read()):
        if g in seen or len(ent) < 3 or (ev is not None and ev < 6): continue
        us = [e for e in ent if LOCAL.search(e[1])]
        if len(us) != 1: continue
        seen.add(g); rows.append((int(p[1]), g, us[0][0], len(ent), us[0][2], tag))
info = {int(i): (n, d) for i, n, d in q("SELECT Id, Name, CONVERT(varchar(10), Date, 120) FROM Meets")}
parts = {int(r[0]) for r in q("SELECT DISTINCT MeetId FROM MeetParticipants WHERE Deleted=0")}
lines = ["-- Generated by scripts/places/team_results.py (Hy-Tek team rankings). Inserts MeetTeamResults (Place, FieldSize, OurScore; no opponent) only where the meet+gender has none. Id-independent; re-runnable.",
         "SET QUOTED_IDENTIFIER ON;", "SET XACT_ABORT ON;", "BEGIN TRANSACTION;", "DECLARE @m INT;", ""]
n = 0
for mid, g, place, size, score, ms in rows:
    mn, md = info[mid]
    if re.search(r'Dual|Triangular|Quad', mn) or mid in parts: continue
    n += 1
    lines.append(f"-- {mn} {'Boys' if g == 1 else 'Girls'}: {place} of {size}, {score:g} pts [{ms}]")
    lines.append(f"SET @m = (SELECT TOP 1 Id FROM Meets WHERE Name=N'{esc(mn)}' AND CAST(Date AS date)='{md}');")
    lines.append(f"IF @m IS NOT NULL AND NOT EXISTS (SELECT 1 FROM MeetTeamResults WHERE MeetId=@m AND Gender={g} AND OpponentMeetParticipantId IS NULL AND Deleted=0) INSERT INTO MeetTeamResults (MeetId, Gender, OpponentMeetParticipantId, OurScore, OpponentScore, Place, FieldSize) VALUES (@m, {g}, NULL, {score}, NULL, {place}, {size});")
lines += ["COMMIT TRANSACTION;", "", f"-- {n} team results"]
open(sys.argv[1], 'w').write('\n'.join(lines) + '\n'); print(n, 'team results from', len({r[5] for r in rows}), 'meets')
for r in rows[:6]: print(r)

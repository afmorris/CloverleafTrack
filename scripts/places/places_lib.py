"""Shared helpers for building finishing-place (MeetPlacings) SQL from result sources.
A source loader yields rows: dict(meet=<dbMeetId>, g=1|2, ev=<DB event name>, name=<athlete name or None for relay>, time=<relay seconds or None>, place=<int>, src=<label>).
build() matches rows to DB performances in the local DB, prints mismatches, and writes Id-independent SQL that inserts a MeetPlacings row
(MeetParticipantId NULL, Place, 0 points) only for performances that have no placing yet."""
import collections, re, subprocess, sys
def q(sql):
    out = subprocess.run(['docker', 'exec', '-i', 'ctf-local-sql', '/opt/mssql-tools18/bin/sqlcmd', '-C', '-I', '-S', 'localhost', '-d', 'ctf', '-U', 'sa', '-P', 'Local#Dev1234', '-W', '-s', '|', '-h', '-1'],
                         input='SET NOCOUNT ON;' + sql, capture_output=True, text=True).stdout
    return [l.split('|') for l in out.strip().split('\n') if l.strip()]
esc = lambda s: s.replace("'", "''")
ALIAS = {'cassy maxwell': 'cassandra maxwell', 'kierston campbell': 'kk campbell', 'isabella messmore': 'izzy messmore', 'jacob schaefer': 'jake schaefer', 'jamere johnson': 'jj johnson'}
def norm(n):
    if ',' in n: l, _, f = n.partition(','); n = f.strip() + ' ' + l.strip()
    n = re.sub(r'[^a-z ]', '', re.sub(r'\s+', ' ', n.replace("'", '').replace('.', '')).lower().strip())
    return ALIAS.get(n, n)
FIELD = {'Long Jump': 'Long Jump', 'Triple Jump': 'Triple Jump', 'Shot Put': 'Shot Put', 'Discus Throw': 'Discus', 'Discus': 'Discus', 'Javelin Throw': 'Javelin', 'Javelin': 'Javelin', 'Pole Vault': 'Pole Vault', 'High Jump': 'High Jump', 'Weight Throw': 'Weight Throw'}
def dbev(t):
    """event title without the gender word -> DB event name (None if unknown)"""
    if re.search(r'\b(JV|Ironwoman|Frosh|Open)\b', t): return None
    t = re.sub(r'\s+(Varsity|Seated|Finals?|Div \d)$', '', t.strip()); t = re.sub(r'\s+\d+"$', '', t)
    if re.search('sprint medley', t, re.I): return '800M Sprint Medley'
    if re.search('distance medley', t, re.I): return '4K Distance Medley'
    if re.search('shuttle hurdle', t, re.I):
        m = re.match(r'^4x(\d+)', t); return f'4x{m.group(1)}M Shuttle Hurdles' if m else None
    if t in FIELD: return FIELD[t]
    m = re.match(r'^4\s*x\s*(\d+)\s*(?:meter|m)?s?\s*relay', t, re.I)
    if m: return f'4x{m.group(1)}M Relay'
    m = re.match(r'^(\d+)\s*(?:meter|m)s?\b', t, re.I)
    if m: return m.group(1) + 'M' + (' Hurdles' if re.search('hurdle', t, re.I) else '')
    if re.match(r'^(1 )?mile', t, re.I): return '1600M'
    return None
def lev(a, b):
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1): cur.append(min(prev[j] + 1, cur[-1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]
def fuzzy(k, x):
    f, _, l = k.partition(' '); f2, _, l2 = norm(x[1]).partition(' ')
    return (l == l2 or lev(l, l2) <= 1) and (f.startswith(f2) or f2.startswith(f) or lev(f, f2) <= 2)
def build(rows, out, label):
    info = {int(i): (n, d) for i, n, d in q("SELECT Id, Name, CONVERT(varchar(10), Date, 120) FROM Meets")}
    parts = {int(r[0]) for r in q("SELECT DISTINCT MeetId FROM MeetParticipants WHERE Deleted=0")}
    perfs = collections.defaultdict(list)   # (meet, g, ev) -> [(pid, athlete name|None, time, placed)]
    for pid, mid, g, en, name, t, pl in q("SELECT p.Id, p.MeetId, e.Gender, e.Name, ISNULL(a.FirstName+' '+a.LastName,''), ISNULL(CAST(p.TimeSeconds AS varchar(30)),''), (SELECT COUNT(*) FROM MeetPlacings x WHERE x.PerformanceId=p.Id) FROM Performances p JOIN Events e ON e.Id=p.EventId LEFT JOIN Athletes a ON a.Id=p.AthleteId WHERE p.ResultStatus=0"):
        perfs[(int(mid), int(g), en)].append((int(pid), name or None, float(t) if t else None, int(pl)))
    lines = [f"-- Generated by scripts/places ({label}). Inserts MeetPlacings (Place, 0 points, no participant) only where the performance has none. Id-independent; re-runnable.",
             "SET QUOTED_IDENTIFIER ON;", "SET XACT_ABORT ON;", "BEGIN TRANSACTION;", "DECLARE @pid INT;", ""]
    seen = set(); n = skip = 0; notes = []
    for r in rows:
        mid = r['meet']
        if mid in parts or re.search(r'Dual|Triangular|Quad', info[mid][0]): skip += 1; continue
        ev = r['ev']
        if 'Seated' in info[mid][0] and not ev.startswith(('Seated', '4x')): ev = r['ev'] = 'Seated ' + ev
        c = perfs.get((mid, r['g'], ev), [])
        if r['name']:
            k = norm(r['name']); hit = [x for x in c if x[1] and norm(x[1]) == k] or [x for x in c if x[1] and fuzzy(k, x)]
        else:
            ts = r['time'] if isinstance(r['time'], list) else [r['time']]
            hit = [x for x in c if x[1] is None and x[2] is not None and any(t is not None and abs(x[2] - t) < 0.06 for t in ts)]
        if len(hit) != 1: notes.append(f"{'AMBIGUOUS' if hit else 'NO MATCH'} {info[mid][0]} {r['ev']} g{r['g']} {r['name'] or r['time']} place {r['place']} [{r['src']}]"); continue
        pid, nm, t, placed = hit[0]
        if placed or pid in seen: continue
        seen.add(pid); n += 1
        mn, md = info[mid]
        lines.append(f"-- {mn}: {nm or 'relay'} {r['ev']} place {r['place']}")
        if nm:
            lines.append(f"SET @pid = (SELECT TOP 1 p.Id FROM Performances p JOIN Athletes a ON a.Id=p.AthleteId JOIN Meets m ON m.Id=p.MeetId JOIN Events e ON e.Id=p.EventId WHERE a.FirstName+N' '+a.LastName=N'{esc(nm)}' AND a.Gender={r['g']} AND m.Name=N'{esc(mn)}' AND CAST(m.Date AS date)='{md}' AND e.Name=N'{esc(r['ev'])}' AND e.Gender={r['g']});")
        else:
            lines.append(f"SET @pid = (SELECT MIN(p.Id) FROM Performances p JOIN Meets m ON m.Id=p.MeetId JOIN Events e ON e.Id=p.EventId WHERE p.AthleteId IS NULL AND m.Name=N'{esc(mn)}' AND CAST(m.Date AS date)='{md}' AND e.Name=N'{esc(r['ev'])}' AND e.Gender={r['g']} AND ABS(p.TimeSeconds-{t})<0.06);")
        lines.append(f"IF @pid IS NOT NULL AND NOT EXISTS (SELECT 1 FROM MeetPlacings WHERE PerformanceId=@pid) INSERT INTO MeetPlacings (MeetId, PerformanceId, MeetParticipantId, Place, FullPoints, SplitPoints) SELECT MeetId, Id, NULL, {r['place']}, 0, 0 FROM Performances WHERE Id=@pid;")
    lines += ["COMMIT TRANSACTION;", "", f"-- {n} placings ({skip} rows skipped: meet has dual participants)"] + [f"-- NOTE: {x}" for x in notes]
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(f"{label}: {n} placings, {skip} skipped (dual), {len(notes)} unmatched"); [print('  NOTE', x) for x in notes[:40]]
    return n

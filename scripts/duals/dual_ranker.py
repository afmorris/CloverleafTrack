#!/usr/bin/env python3 -I
"""Per-opponent dual-meet placings from transcribed full event results.
usage: dual_ranker.py <data.txt> <DB meet name> <out.sql> <CODE=School>[,...] [--scores]
data lines: g|event|schoolCode|name|mark   (C = Cloverleaf; relays have a blank name; marks are times or feet-inches 'F-I'; 'DQ'/'NM'/'' are unranked)
Each Cloverleaf row is matched to its DB performance (event + last name + mark); its place is its rank among Cloverleaf + that opponent's rows (ties share the average points of
the places they span; relays: only 1st scores, 5). Prints a REVIEW list (marks that differ from the DB, rows with no DB performance) and the computed team totals;
--scores also writes them to MeetTeamResults (use only when every event is on the sheets)."""
import os, re, sys, collections
H = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(H, '../places'))
from places_lib import q, esc, norm
data, mname, out, opps = sys.argv[1], sys.argv[2], sys.argv[3], dict(x.split('=') for x in sys.argv[4].split(','))
WANT_SCORES = '--scores' in sys.argv
def val(s):
    s = s.strip().replace(';', ':')
    m = re.match(r"^(\d+)-(\d+(?:\.\d+)?)$", s)
    if m: return 'field', int(m.group(1)) * 12 + float(m.group(2))
    m = re.match(r'^(?:(\d+):)?(\d+(?:\.\d+)?)$', s)
    return ('run', (int(m.group(1)) * 60 if m.group(1) else 0) + float(m.group(2))) if m else (None, None)
TEMPL = {1: 5.0, 2: 3.0, 3: 1.0}
rows = []
for l in open(data):
    if l.startswith('#') or not l.strip(): continue
    f = l.rstrip('\n').split('|')
    g, ev, sc, nm, mk = f[:5]; tb = int(f[5]) if len(f) > 5 and f[5] else 0
    k, v = val(mk); rows.append(dict(g=int(g), ev=ev, sc=sc, name=nm.strip(), mark=mk.strip(), kind=k, v=v, tb=tb))
mid, mdate = q(f"SELECT Id, CONVERT(varchar(10), Date, 120) FROM Meets WHERE Name=N'{esc(mname)}'")[0]; mid = int(mid)
perfs = collections.defaultdict(list)
for pid, g, en, fn, ln, t, d in q(f"SELECT p.Id, e.Gender, e.Name, ISNULL(a.FirstName,''), ISNULL(a.LastName,''), ISNULL(CAST(p.TimeSeconds AS varchar(30)),''), ISNULL(CAST(p.DistanceInches AS varchar(30)),'') FROM Performances p JOIN Events e ON e.Id=p.EventId LEFT JOIN Athletes a ON a.Id=p.AthleteId WHERE p.MeetId={mid} AND p.ResultStatus=0"):
    perfs[(int(g), en)].append((int(pid), fn, ln, float(t) if t else None, float(d) if d else None))
groups = collections.defaultdict(list)
for r in rows: groups[(r['g'], r['ev'])].append(r)
refine = []; review = []; lines = ["-- Generated by scripts/duals/dual_ranker.py from transcribed dual-meet event sheets. Per-opponent placings (rank among the two teams). Id-independent; re-runnable.",
                      "SET QUOTED_IDENTIFIER ON;", "SET XACT_ABORT ON;", "BEGIN TRANSACTION;", "DECLARE @m INT, @t INT, @pid INT, @mp INT;",
                      "SET @t = (SELECT TOP 1 Id FROM ScoringTemplates WHERE Name LIKE N'Dual Meet%' AND Deleted=0);",
                      f"SET @m = (SELECT TOP 1 Id FROM Meets WHERE Name=N'{esc(mname)}' AND CAST(Date AS date)='{mdate}');", "IF @m IS NULL THROW 50050, 'meet missing', 1;",
                      f"UPDATE Meets SET MeetType={2 if len(opps) > 1 else 1}, ScoringTemplateId=@t WHERE Id=@m;"]
for i, (code, sch) in enumerate(opps.items()):
    lines.append(f"IF NOT EXISTS (SELECT 1 FROM MeetParticipants mp JOIN Schools s ON s.Id=mp.SchoolId WHERE mp.MeetId=@m AND s.Name=N'{sch}' AND mp.Deleted=0) INSERT INTO MeetParticipants (MeetId, SchoolId, Gender, SortOrder) SELECT @m, Id, NULL, {i} FROM Schools WHERE Name=N'{sch}';")
totals = collections.defaultdict(lambda: [0.0, 0.0]); n = 0; seen_events = collections.defaultdict(set)
for (g, ev), rs in sorted(groups.items(), key=lambda x: str(x[0])):
    if ev.startswith('Seated'): continue   # seated events never count toward team scores
    isrelay = ev.startswith('4x') or 'Medley' in ev
    for code, sch in opps.items():
        pool = [r for r in rs if r['sc'] in ('C', code) and r['v'] is not None]
        if not pool: continue
        seen_events[(g, code)].add(ev)
        key = (lambda r: (r['v'], r['tb'])) if pool[0]['kind'] == 'run' else (lambda r: (-r['v'], r['tb']))
        pool.sort(key=key)
        # ranks with ties
        i = 0
        while i < len(pool):
            j = i
            while j + 1 < len(pool) and abs(key(pool[j + 1])[0] - key(pool[i])[0]) < 1e-9 and key(pool[j + 1])[1] == key(pool[i])[1]: j += 1
            place = i + 1
            pts = (5.0 if place == 1 and isrelay else 0.0) if isrelay else sum(TEMPL.get(p, 0.0) for p in range(place, j + 2)) / (j - i + 1)
            for r in pool[i:j + 1]:
                r['place_' + code] = place; r['pts_' + code] = pts
                totals[(g, code)][0 if r['sc'] == 'C' else 1] += pts
            i = j + 1
    cl = [r for r in rs if r['sc'] == 'C']
    cand = perfs.get((g, ev), [])
    for r in cl:
        if r['v'] is None: continue
        if isrelay: hit = [c for c in cand if c[1] == '' and c[2] == '' and c[3] is not None and abs(c[3] - r['v']) < (1.0 if c[3] == int(c[3]) else 0.15)]
        else:
            last = norm(r['name'].split()[-1]) if r['name'] else ''
            hit = [c for c in cand if norm(c[2]) == last or (len(last) >= 4 and norm(c[2]).startswith(last[:4]))]
            if len(hit) > 1: hit = sorted(hit, key=lambda c: abs((c[3] if c[3] is not None else c[4]) - r['v']))[:1]
        if len(hit) != 1: review.append(f"NO DB ROW g{g} {ev} {r['name'] or 'relay'} {r['mark']}"); continue
        pid, fn, ln, t, d = hit[0]; dv = t if t is not None else d
        tol = 0.6 if r['kind'] == 'field' else (0.3 if r['v'] > 120 else 0.15)
        if r['kind'] == 'run' and dv == int(dv) and 0 <= r['v'] - dv < 1.0: refine.append((g, ev, fn, ln, dv, r['v'], t is not None, isrelay)); tol = 1.0
        if abs(dv - r['v']) > tol: review.append(f"MARK DIFFERS g{g} {ev} {fn} {ln}: sheet {r['mark']} vs DB {dv}")
        for code, sch in opps.items():
            if 'place_' + code not in r: continue
            n += 1; place = r['place_' + code]; pts = r['pts_' + code]
            lines.append(f"-- {sch} {'Boys' if g == 1 else 'Girls'} {ev}: place {place} {fn} {ln} {r['mark']}".replace('  ', ' '))
            if isrelay: lines.append(f"SET @pid = (SELECT TOP 1 p.Id FROM Performances p JOIN Events e ON e.Id=p.EventId WHERE p.MeetId=@m AND p.AthleteId IS NULL AND e.Gender={g} AND e.Name=N'{ev}' AND ABS(p.TimeSeconds-{t})<0.006);")
            else: lines.append(f"SET @pid = (SELECT TOP 1 p.Id FROM Performances p JOIN Athletes a ON a.Id=p.AthleteId JOIN Events e ON e.Id=p.EventId WHERE p.MeetId=@m AND a.FirstName=N'{esc(fn)}' AND a.LastName=N'{esc(ln)}' AND e.Gender={g} AND e.Name=N'{ev}');")
            lines.append(f"SET @mp = (SELECT TOP 1 mp.Id FROM MeetParticipants mp JOIN Schools s ON s.Id=mp.SchoolId WHERE mp.MeetId=@m AND s.Name=N'{sch}' AND mp.Deleted=0);")
            lines.append(f"IF @pid IS NOT NULL AND @mp IS NOT NULL AND NOT EXISTS (SELECT 1 FROM MeetPlacings WHERE PerformanceId=@pid AND MeetParticipantId=@mp) INSERT INTO MeetPlacings (MeetId, PerformanceId, MeetParticipantId, Place, FullPoints, SplitPoints) VALUES (@m, @pid, @mp, {place}, {round(pts, 2)}, {round(pts / 4, 2) if isrelay else round(pts, 2)});")
if WANT_SCORES:
    for (g, code), (a, b) in sorted(totals.items()):
        sch = opps[code]
        lines.append(f"SET @mp = (SELECT TOP 1 mp.Id FROM MeetParticipants mp JOIN Schools s ON s.Id=mp.SchoolId WHERE mp.MeetId=@m AND s.Name=N'{sch}' AND mp.Deleted=0);")
        lines.append(f"IF @mp IS NOT NULL AND NOT EXISTS (SELECT 1 FROM MeetTeamResults WHERE MeetId=@m AND Gender={g} AND OpponentMeetParticipantId=@mp AND Deleted=0) INSERT INTO MeetTeamResults (MeetId, Gender, OpponentMeetParticipantId, OurScore, OpponentScore, Place, FieldSize) VALUES (@m, {g}, @mp, {round(a, 2)}, {round(b, 2)}, NULL, NULL);")
lines += ["COMMIT TRANSACTION;", "", f"-- {n} placings"] + [f"-- REVIEW: {x}" for x in review]
open(out, 'w').write('\n'.join(lines) + '\n')
open(out + '.refine', 'w').write('\n'.join(f"{g}|{ev}|{fn} {ln}|{dv}|{sv}" for g, ev, fn, ln, dv, sv, ind, rel in refine) + '\n')
print(n, 'placings;', len(review), 'review items')
for (g, code), (a, b) in sorted(totals.items()): print(f"computed {'Boys' if g == 1 else 'Girls'} vs {opps[code]}: CLO {a:g} - {b:g}  ({len(seen_events[(g, code)])} events)")
for x in review: print('  ', x)

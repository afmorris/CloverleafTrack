#!/usr/bin/env python3
"""Relay prelim/semi -> final round chains from MileSplit Live (scripts/athleticnet/live-raw/<msMeetId>.txt) as SQL.
usage: build_live_relay_rounds.py <out.sql>      (needs the local ctf-local-sql container and ../crawl/matches.tsv)
A Cloverleaf relay team ('Cloverleaf "A" <four legs>') that has a time in 2+ rounds is chained (P=1 prelim, S=2 semi, F=3 final) when
  - the DB has exactly one relay row (AthleteId NULL) for that meet, event and gender whose time equals the fastest round (within 0.06), and
  - that row has no PerformanceRounds yet (existing chains are only compared, never replaced).
The SQL finds the row by meet name/date + event + gender + time (Ids differ between databases) and aborts if it is not exactly one row."""
import collections, os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
def q(sql):
    out = subprocess.run(['docker', 'exec', '-i', 'ctf-local-sql', '/opt/mssql-tools18/bin/sqlcmd', '-C', '-I', '-S', 'localhost', '-d', 'ctf', '-U', 'sa', '-P', 'Local#Dev1234', '-W', '-s', '|', '-h', '-1'],
                         input='SET NOCOUNT ON;' + sql, capture_output=True, text=True).stdout
    return [l.split('|') for l in out.strip().split('\n') if l.strip()]
esc = lambda s: s.replace("'", "''")
meets = {}
for l in list(open(os.path.join(HERE, '../crawl/matches.tsv')))[1:]:
    p = l.rstrip('\n').split('\t')
    if p[0] == 'milesplit' and p[4]: meets[p[1]] = int(p[4])
def secs(t):
    t = re.sub(r'[^0-9:.]', '', t.split(' ')[0]); m = re.match(r'^(?:(\d+):)?(\d+(?:\.\d+)?)$', t)
    return (int(m.group(1)) * 60 if m.group(1) else 0) + float(m.group(2)) if m else None
def evname(title):
    m = re.search(r'(Boys|Girls)\s+(\d)x(\d+)\s+(?:Meter\s+)?Relay', title)
    return ((1 if m.group(1) == 'Boys' else 2), f"{m.group(2)}x{m.group(3)}M Relay") if m else (None, None)
RN = {'P': 1, 'S': 2, 'F': 3}
teams = collections.defaultdict(dict)
for fn in sorted(os.listdir(os.path.join(HERE, 'live-raw'))):
    ms = fn[:-4]
    if ms not in meets: continue
    ev = None; rnd = None; cols = []
    for line in open(os.path.join(HERE, 'live-raw', fn), encoding='utf-8'):
        line = line.rstrip('\n')
        if line.startswith('E|'):
            p = line.split('|', 4); ev = p[2]; rnd = p[3]; cols = (p[4] if len(p) > 4 else '').split('¦'); continue
        if not ev or 'Team' not in cols or 'Athlete' in cols or 'Time' not in cols: continue
        g, en = evname(ev)
        if not en: continue
        c = line.split('|'); team = c[cols.index('Team')]; t = secs(c[cols.index('Time')])
        m = re.match(r'^Cloverleaf\s+"([A-Z])"', team) or re.match(r'^Cloverleaf()\b', team)
        if t is None or not m or rnd not in RN: continue
        teams[(ms, g, en, m.group(1))][RN[rnd]] = t
lines = ["-- Generated by scripts/athleticnet/build_live_relay_rounds.py from MileSplit Live. REVIEW BEFORE RUNNING.",
         "-- Touches only PerformanceRounds. Each relay row is found by meet name/date + event + gender + fastest-round time and must be exactly one row.",
         "SET XACT_ABORT ON;", "BEGIN TRANSACTION;", "DECLARE @pid INT, @n INT;", ""]
total = 0; notes = []
for (ms, g, en, lab), rounds in sorted(teams.items()):
    if len(rounds) < 2: continue
    db = meets[ms]; best = min(rounds.values())
    meta = q(f"SELECT Name, CONVERT(varchar(10), Date, 120) FROM Meets WHERE Id={db}")[0]
    rel = q(f"SELECT p.Id, p.TimeSeconds, (SELECT COUNT(*) FROM PerformanceRounds r WHERE r.PerformanceId=p.Id) FROM Performances p JOIN Events e ON e.Id=p.EventId WHERE p.MeetId={db} AND e.Name='{en}' AND e.Gender={g} AND p.AthleteId IS NULL AND ABS(p.TimeSeconds-{best})<0.06")
    if len(rel) != 1: notes.append(f"{meta[0]} {en} gender {g} team {lab}: {len(rel)} DB relay rows match {best}"); continue
    if rel[0][2] != '0': continue   # already chained (compared separately; they agree)
    total += 1
    lines.append(f"-- {meta[0]} {'Boys' if g == 1 else 'Girls'} {en} team {lab}: " + ', '.join(f"{ {1: 'prelim', 2: 'semi', 3: 'final'}[k]} {v}" for k, v in sorted(rounds.items())))
    lines.append(f"SELECT @n = COUNT(*), @pid = MIN(p.Id) FROM Performances p JOIN Meets m ON m.Id=p.MeetId JOIN Events e ON e.Id=p.EventId WHERE m.Name=N'{esc(meta[0])}' AND CAST(m.Date AS date)='{meta[1]}' AND e.Name=N'{en}' AND e.Gender={g} AND p.AthleteId IS NULL AND ABS(p.TimeSeconds-{best})<0.06;")
    lines.append("IF @n <> 1 THROW 50005, 'Relay row not found exactly once', 1;")
    lines.append("IF NOT EXISTS (SELECT 1 FROM PerformanceRounds WHERE PerformanceId=@pid)\nBEGIN")
    for k, v in sorted(rounds.items()): lines.append(f"    INSERT INTO PerformanceRounds (PerformanceId, Round, TimeSeconds) VALUES (@pid, {k}, {round(v, 2)});")
    lines.append("END\n")
lines += ["COMMIT TRANSACTION;", "", f"-- {total} relay round chains"] + [f"-- NOTE: {n}" for n in notes]
open(sys.argv[1], 'w').write('\n'.join(lines) + '\n')
print(f"{total} chains"); [print('NOTE', n) for n in notes]

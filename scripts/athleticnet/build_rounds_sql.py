#!/usr/bin/env python3 -I
"""Builds one reviewable SQL script from scraped athletic.net data.

usage: build_rounds_sql.py <data-dir> <out.sql> <dbMeetId> [<dbMeetId> ...]

<data-dir>/<id>/an.txt : scraped athletic.net output (first line = meet title; lines
                         "<gender>/<div>/<event>|<round> I place~grade~name~mark~team~athleteId" (individual),
                         "<gender>/<div>/<event>|<round> R place time teamName" (relay), and a final "#SERIES {json}")
<data-dir>/<id>/db.txt : read-only dump, one line per Performance:
                         Id|Gender|EventName|Athletes|TimeSeconds|DistanceInches|AttemptCount

Rounds only exist when an athlete/relay has 2+ rounds for the same event. Attempt series are written only when
2+ attempts are recorded and at least one is a valid mark. Every block re-asserts the expected best mark so a bad
match aborts the transaction. Performances rows are never modified, and relay members are never touched.
"""
import json, os, re, sys
from collections import defaultdict

data_dir, out = sys.argv[1], sys.argv[2]
meets = sys.argv[3:]

EVENTS = {'100m': '100M', '200m': '200M', '400m': '400M', '800m': '800M', '1600m': '1600M', '3200m': '3200M',
          '110mh': '110M Hurdles', '100mh': '100M Hurdles', '300mh': '300M Hurdles',
          '4x100m': '4x100M Relay', '4x200m': '4x200M Relay', '4x400m': '4x400M Relay', '4x800m': '4x800M Relay',
          'shot': 'Shot Put', 'discus': 'Discus', 'lj': 'Long Jump', 'tj': 'Triple Jump',
          '60m': '60M', '60mh': '60M Hurdles'}
ROUND = {'Prelims': 1, 'Semi-Finals': 2, 'Finals': 3}
RNAME = {1: 'Prelim', 2: 'Semi', 3: 'Final'}
RELAY_CODES = {'4x100m', '4x200m', '4x400m', '4x800m'}
FIELD_CODES = {'shot', 'discus', 'lj', 'tj'}  # field prelims/finals are attempts, not PerformanceRounds

def secs(s):
    m = re.match(r'\s*([\d:.]+)', s)
    if not m: return None
    s = m.group(1)
    if ':' in s:
        mi, r = s.split(':'); return int(mi) * 60 + float(r)
    return float(s)

def inches(s):
    m = re.match(r"(\d+)' ([\d.]+)\"", s)
    return int(m.group(1)) * 12 + float(m.group(2)) if m else None

def gender(g): return {'m': 1, 'f': 2}.get(g)

lines = ["-- Generated by scripts/athleticnet/build_rounds_sql.py from athletic.net data. REVIEW BEFORE RUNNING.",
         "-- Requires docs/migration_performance_rounds.sql first. Touches only PerformanceRounds / PerformanceAttempts",
         "-- (Performances is never written, so sp_RebuildLeaderboards is not needed; relay members are never touched).",
         "-- Each block re-asserts the expected mark and aborts the whole transaction on a mismatch.",
         "SET XACT_ABORT ON;", "BEGIN TRANSACTION;", ""]
notes = []
tot_chain = tot_series = 0

for mid in meets:
    an = open(os.path.join(data_dir, mid, 'an.txt')).read()
    body, _, sj = an.partition('#SERIES ')
    series = json.loads(sj.strip() or '{}')
    rows = body.strip().split('\n')
    title = rows[0]
    perfs = defaultdict(list)
    for line in open(os.path.join(data_dir, mid, 'db.txt')):
        p = line.rstrip('\n').split('|')
        if len(p) < 7: continue
        perfs[(int(p[1]), p[2])].append((int(p[0]), None if p[4] == 'NULL' else float(p[4]), None if p[5] == 'NULL' else float(p[5]), p[3]))

    hints_path = os.path.join(data_dir, mid, 'names.json')
    hints = json.load(open(hints_path)) if os.path.exists(hints_path) else {}

    def find(g, ev, time=None, dist=None, hint=None):
        c = [x for x in perfs[(g, ev)] if (time is not None and x[1] is not None and abs(x[1] - time) < 0.006)
             or (dist is not None and x[2] is not None and abs(x[2] - dist) < 0.006)]
        if len(c) > 1 and hint:
            c = [x for x in c if hint in x[3]]
        return c[0] if len(c) == 1 else (None if not c else 'AMBIG')

    lines += [f"-- ===== DB meet {mid}: {title} =====", ""]
    ind = defaultdict(dict); rel = defaultdict(dict); names = {}
    for line in rows[1:]:
        if not line.strip(): continue
        head, kind, rest = re.match(r'^(\S+)\s([IR])\s(.*)$', line).groups()
        path, sub = head.split('|')
        g = gender(path[0]); code = path.split('/')[-1]
        if g is None or sub not in ROUND or code not in EVENTS:
            if sub in ROUND and code not in EVENTS: notes.append(f"UNSUPPORTED EVENT in {mid}: {code}")
            continue
        if kind == 'I':
            if code in RELAY_CODES or code in FIELD_CODES: continue
            f = rest.split('~'); t = secs(f[3]) if len(f) >= 6 else None
            if t is None: continue
            ind[(g, code, f[-1])][ROUND[sub]] = t; names[f[-1]] = f[2]
        else:
            m = re.match(r'^\S+\s+(\S+)\s+(Cloverleaf.*?)\s*$', rest)
            if not m: continue
            t = secs(m.group(1))
            if t is None: continue
            rel[(g, code, re.sub(r'\s*Q$', '', m.group(2)))][ROUND[sub]] = t

    def emit_chain(label, g, ev, rounds, hint_ok=False):
        global tot_chain
        best = min(rounds.values()); p = find(g, ev, time=best, hint=(label if hint_ok else None))
        if p is None or p == 'AMBIG':
            notes.append(f"{'AMBIGUOUS' if p else 'UNMATCHED'} rounds in {mid}: {label} {ev} best={best}"); return
        tot_chain += 1
        lines.append(f"-- {label} {ev} ({'M' if g == 1 else 'F'}): " + ' -> '.join(f"{RNAME[r]} {t}" for r, t in sorted(rounds.items())))
        lines.append(f"IF NOT EXISTS (SELECT 1 FROM Performances WHERE Id={p[0]} AND MeetId={mid} AND ABS(TimeSeconds-{best})<0.006) THROW 50001, 'Mark mismatch for performance {p[0]}', 1;")
        lines.append(f"DELETE FROM PerformanceRounds WHERE PerformanceId={p[0]};")
        for r, t in sorted(rounds.items()):
            lines.append(f"INSERT INTO PerformanceRounds (PerformanceId, Round, TimeSeconds) VALUES ({p[0]}, {r}, {t});")
        lines.append("")

    for (g, code, aid), rounds in sorted(ind.items()):
        if len(rounds) >= 2: emit_chain(names[aid], g, EVENTS[code], rounds, hint_ok=True)
    for (g, code, team), rounds in sorted(rel.items()):
        if len(rounds) >= 2: emit_chain(team, g, EVENTS[code], rounds)

    for href, athletes in series.items():
        g = gender(href[0]); code = href.split('/')[-1]
        if g is None or code not in EVENTS:
            if code not in EVENTS: notes.append(f"UNSUPPORTED EVENT in {mid}: {code}")
            continue
        ev = EVENTS[code]
        for a in athletes:
            att = ['Foul' if x.upper() == 'FOUL' else ('Pass' if x.upper() == 'PASS' else x) for x in a['att']]
            marks = [inches(x) for x in att if x not in ('Foul', 'Pass', '')]
            marks = [m for m in marks if m is not None]
            if len([x for x in att if x]) < 2 or not marks: continue
            best = max(marks); p = find(g, ev, dist=best, hint=hints.get(a['id']))
            if p is None or p == 'AMBIG':
                notes.append(f"{'AMBIGUOUS' if p else 'UNMATCHED'} series in {mid}: athlete {a['id']} {ev} ({href[0]}) best={best}"); continue
            tot_series += 1
            lines.append(f"-- {p[3]} {ev} ({'M' if g == 1 else 'F'}): {', '.join(x for x in att if x)}")
            lines.append(f"IF NOT EXISTS (SELECT 1 FROM Performances WHERE Id={p[0]} AND MeetId={mid} AND ABS(DistanceInches-{best})<0.006) THROW 50002, 'Mark mismatch for performance {p[0]}', 1;")
            lines.append(f"DELETE FROM PerformanceAttempts WHERE PerformanceId={p[0]};")
            for i, x in enumerate(att, 1):
                if x == '': continue
                if x in ('Foul', 'Pass'):
                    lines.append(f"INSERT INTO PerformanceAttempts (PerformanceId, AttemptNumber, DistanceInches, IsFoul, IsPass) VALUES ({p[0]}, {i}, NULL, {int(x == 'Foul')}, {int(x == 'Pass')});")
                else:
                    lines.append(f"INSERT INTO PerformanceAttempts (PerformanceId, AttemptNumber, DistanceInches, IsFoul, IsPass) VALUES ({p[0]}, {i}, {inches(x)}, 0, 0);")
            lines.append("")

lines += ["COMMIT TRANSACTION;", "", f"-- {tot_chain} round chains, {tot_series} attempt series"]
lines += [f"-- NOTE: {n}" for n in notes]
open(out, 'w').write('\n'.join(lines) + '\n')
print(f"{tot_chain} chains, {tot_series} series"); [print('NOTE', n) for n in notes]

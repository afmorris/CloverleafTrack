#!/usr/bin/env python3 -I
"""Builds reviewable SQL for high jump / pole vault bar ladders transcribed from scorer-sheet scans.

usage: build_bars_sql.py <data-dir> <out.sql> <dbMeetId> [...]
<data-dir>/<id>/bars.txt : "gender|event|DB athlete name|height:outcome;height:outcome;..."
    heights like 5-2 (feet-inches), outcome one of O XO XXO XXX P XP XXP (X miss, O clear, P pass; already normalised
    to the standard notation - sheets that used the inverted notation are converted when transcribing).
<data-dir>/<id>/db.txt   : read-only dump  Id|Gender|EventName|Athlete|TimeSeconds|DistanceInches|AttemptCount
Each block asserts the stored mark equals the best cleared bar. No-height athletes (nothing cleared) are matched
only if the DB has a row for them (it usually does not) and then write the ladder without asserting a mark.
Performances is never modified.
"""
import os, re, sys
from collections import defaultdict
data_dir, out = sys.argv[1], sys.argv[2]
VALID = {'O', 'XO', 'XXO', 'XXX', 'P', 'XP', 'XXP', 'X', 'XX'}   # X / XX: final misses that ended the competition (migration_performance_bars_x.sql)
def inches(s):
    f, i = s.split('-'); return int(f) * 12 + float(i)
lines = ["-- Generated by scripts/athleticnet/build_bars_sql.py from transcribed scorer sheets. REVIEW BEFORE RUNNING.",
         "-- Requires docs/migration_performance_bars.sql first. Touches only PerformanceBars; Performances is never written.",
         "SET XACT_ABORT ON;", "BEGIN TRANSACTION;", ""]
SKIP = bool(os.environ.get('SKIP_EXISTING'))   # insert-only and Id-independent: the performance is looked up by athlete name, meet name/date, event and exact mark
if SKIP: lines += ["DECLARE @pid INT;", ""]
esc = lambda s: s.replace("'", "''")
notes = []; total = 0
for mid in sys.argv[3:]:
    perfs = defaultdict(list); nohe = defaultdict(list)
    for l in open(os.path.join(data_dir, mid, 'db.txt')):
        p = l.rstrip('\n').split('|')
        if len(p) >= 7 and p[5] != 'NULL': perfs[(int(p[1]), p[2], p[3])].append((int(p[0]), float(p[5])))
        elif len(p) >= 8 and p[5] == 'NULL' and p[7] == '2': nohe[(int(p[1]), p[2], p[3])].append(int(p[0]))   # no-height (NH) rows
    lines += [f"-- ===== DB meet {mid} =====", ""]
    mname, mdate = (open(os.path.join(data_dir, mid, 'meta.txt')).read().strip().split('|') if os.path.exists(os.path.join(data_dir, mid, 'meta.txt')) else ('', ''))
    def lookup(name, g, ev, cond): return (f"SET @pid = (SELECT TOP 1 p.Id FROM Performances p JOIN Athletes a ON a.Id=p.AthleteId JOIN Meets m ON m.Id=p.MeetId JOIN Events e ON e.Id=p.EventId "
                                          f"WHERE a.FirstName+N' '+a.LastName=N'{esc(name)}' AND a.Gender={g} AND m.Name=N'{esc(mname)}' AND CAST(m.Date AS date)='{mdate}' AND e.Name=N'{esc(ev)}' AND e.Gender={g} AND {cond});")
    for raw in open(os.path.join(data_dir, mid, 'bars.txt')):
        raw = raw.strip()
        if not raw or raw.startswith('#'): continue
        g, ev, name, ladder = raw.split('|')
        g = int(g)
        bars = []
        for part in ladder.split(';'):
            h, o = part.split(':')
            if o not in VALID: notes.append(f"BAD OUTCOME meet {mid}: {name} {h}:{o}"); bars = None; break
            bars.append((inches(h), o, h))
        if not bars: continue
        cleared = [b[0] for b in bars if b[1].endswith('O')]
        c = perfs.get((g, ev, name), [])
        if not cleared:
            nh = nohe.get((g, ev, name), [])
            if len(nh) != 1: notes.append(f"NO HEIGHT meet {mid}: {name} {ev} (no performance row to attach to)"); continue
            pid = nh[0]; total += 1
            lines.append(f"-- {name} {ev} ({'M' if g == 1 else 'F'}) no height: " + ', '.join(f"{b[2]} {b[1]}" for b in bars))
            if SKIP:
                lines.append(lookup(name, g, ev, "p.ResultStatus=2")); lines.append("IF @pid IS NOT NULL AND NOT EXISTS (SELECT 1 FROM PerformanceBars WHERE PerformanceId=@pid)\nBEGIN"); pid = '@pid'
            else:
                lines.append(f"IF NOT EXISTS (SELECT 1 FROM Performances WHERE Id={pid} AND MeetId={mid} AND ResultStatus=2) THROW 50003, 'Not a no-height row: performance {pid}', 1;")
                lines.append(f"DELETE FROM PerformanceBars WHERE PerformanceId={pid};")
            for h, o, _ in bars: lines.append(f"INSERT INTO PerformanceBars (PerformanceId, HeightInches, Outcome) VALUES ({pid}, {h}, '{o}');")
            if SKIP: lines.append("END")
            lines.append(""); continue
        best = max(cleared)
        if len(c) != 1:
            notes.append(f"{'AMBIGUOUS' if c else 'NO PERFORMANCE'} meet {mid}: {name} {ev} (gender {g})"); continue
        pid, dist = c[0]
        if abs(dist - best) > 0.006:
            notes.append(f"MARK MISMATCH meet {mid}: {name} {ev}: sheet best {best} vs DB {dist}"); continue
        total += 1
        lines.append(f"-- {name} {ev} ({'M' if g == 1 else 'F'}): " + ', '.join(f"{b[2]} {b[1]}" for b in bars))
        if SKIP:
            lines.append(lookup(name, g, ev, f"ABS(p.DistanceInches-{best})<0.006")); lines.append("IF @pid IS NOT NULL AND NOT EXISTS (SELECT 1 FROM PerformanceBars WHERE PerformanceId=@pid)\nBEGIN"); pid = '@pid'
        else:
            lines.append(f"IF NOT EXISTS (SELECT 1 FROM Performances WHERE Id={pid} AND MeetId={mid} AND ABS(DistanceInches-{best})<0.006) THROW 50003, 'Mark mismatch for performance {pid}', 1;")
            lines.append(f"DELETE FROM PerformanceBars WHERE PerformanceId={pid};")
        for h, o, _ in bars:
            lines.append(f"INSERT INTO PerformanceBars (PerformanceId, HeightInches, Outcome) VALUES ({pid}, {h}, '{o}');")
        if SKIP: lines.append("END")
        lines.append("")
lines += ["COMMIT TRANSACTION;", "", f"-- {total} bar ladders"] + [f"-- NOTE: {n}" for n in notes]
open(out, 'w').write('\n'.join(lines) + '\n')
print(f"{total} ladders"); [print('NOTE', n) for n in notes]

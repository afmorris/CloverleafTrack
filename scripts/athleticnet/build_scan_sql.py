#!/usr/bin/env python3 -I
"""Builds reviewable SQL for attempt series transcribed from scorer-sheet scans.

usage: build_scan_sql.py <data-dir> <out.sql> <dbMeetId> [...]
<data-dir>/<id>/sheets.txt : "gender|event|DB athlete name|a1;a2;..." (gender 1/2; F-I distances, F foul, P pass)
<data-dir>/<id>/db.txt     : read-only dump  Id|Gender|EventName|Athlete|TimeSeconds|DistanceInches|AttemptCount
Matches by (gender, event, athlete name) and asserts the sheet's best attempt equals the stored mark, so a
misread best (or wrong athlete) aborts the transaction. Performances rows are never modified.
"""
import os, re, sys
from collections import defaultdict
data_dir, out = sys.argv[1], sys.argv[2]
lines = ["-- Generated by scripts/athleticnet/build_scan_sql.py from transcribed scorer sheets. REVIEW BEFORE RUNNING.",
         "-- Touches only PerformanceAttempts (table already exists). Performances is never written; each block asserts the stored mark.",
         "SET XACT_ABORT ON;", "BEGIN TRANSACTION;", ""]
notes = []; total = 0
def inches(s):
    m = re.match(r'^(\d+)-([\d.]+)$', s)
    return int(m.group(1)) * 12 + float(m.group(2))
def pretty(s):
    if s in ('F', 'P', ''): return {'F': 'Foul', 'P': 'Pass', '': ''}[s]
    f, i = s.split('-'); return f"{f}' {i}\""
for mid in sys.argv[3:]:
    perfs = defaultdict(list)
    for l in open(os.path.join(data_dir, mid, 'db.txt')):
        p = l.rstrip('\n').split('|')
        if len(p) >= 7 and p[5] != 'NULL': perfs[(int(p[1]), p[2], p[3])].append((int(p[0]), float(p[5])))
    lines += [f"-- ===== DB meet {mid} =====", ""]
    for raw in open(os.path.join(data_dir, mid, 'sheets.txt')):
        raw = raw.strip()
        if not raw or raw.startswith('#'): continue
        g, ev, name, att = raw.split('|')
        g = int(g); att = att.split(';')
        marks = [inches(a) for a in att if a not in ('F', 'P', '')]
        if not marks or len([a for a in att if a]) < 2: continue  # need a real series (2+ recorded attempts)
        best = max(marks); c = perfs.get((g, ev, name), [])
        if len(c) != 1:
            notes.append(f"{'AMBIGUOUS' if c else 'NO PERFORMANCE'} meet {mid}: {name} {ev} (gender {g})"); continue
        pid, dist = c[0]
        if abs(dist - best) > 0.006:
            notes.append(f"MARK MISMATCH meet {mid}: {name} {ev}: sheet best {best} vs DB {dist} (attempts {';'.join(att)})"); continue
        total += 1
        lines.append(f"-- {name} {ev} ({'M' if g == 1 else 'F'}): {', '.join(pretty(a) for a in att if a)}")
        lines.append(f"IF NOT EXISTS (SELECT 1 FROM Performances WHERE Id={pid} AND MeetId={mid} AND ABS(DistanceInches-{best})<0.006) THROW 50002, 'Mark mismatch for performance {pid}', 1;")
        lines.append(f"DELETE FROM PerformanceAttempts WHERE PerformanceId={pid};")
        for i, a in enumerate(att, 1):
            if a == '': continue
            if a in ('F', 'P'):
                lines.append(f"INSERT INTO PerformanceAttempts (PerformanceId, AttemptNumber, DistanceInches, IsFoul, IsPass) VALUES ({pid}, {i}, NULL, {int(a == 'F')}, {int(a == 'P')});")
            else:
                lines.append(f"INSERT INTO PerformanceAttempts (PerformanceId, AttemptNumber, DistanceInches, IsFoul, IsPass) VALUES ({pid}, {i}, {inches(a)}, 0, 0);")
        lines.append("")
lines += ["COMMIT TRANSACTION;", "", f"-- {total} attempt series"] + [f"-- NOTE: {n}" for n in notes]
open(out, 'w').write('\n'.join(lines) + '\n')
print(f"{total} series"); [print('NOTE', n) for n in notes]

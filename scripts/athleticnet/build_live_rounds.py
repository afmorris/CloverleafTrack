#!/usr/bin/env python3 -I
"""Builds SQL for prelim/semi -> final round chains from MileSplit Live (convert_live.py output).
usage: build_live_rounds.py <data-dir> <out.sql> <dbMeetId> [...]
<data-dir>/<id>/rounds.txt : "gender|event|DB athlete name|P:sec;S:sec;F:sec" (P=1 prelim, S=2 semi, F=3 final; 2+ rounds)
<data-dir>/<id>/db.txt     : Id|Gender|EventName|Athlete|TimeSeconds|DistanceInches|AttemptCount
Each block asserts the stored time equals the fastest round (best across rounds), skips performances that already have rounds, and never
modifies Performances."""
import os, sys
from collections import defaultdict
data_dir, out = sys.argv[1], sys.argv[2]
RN = {'P': 1, 'S': 2, 'F': 3}
NAME = {1: 'prelim', 2: 'semi', 3: 'final'}
lines = ["-- Generated by scripts/athleticnet/build_live_rounds.py from MileSplit Live. REVIEW BEFORE RUNNING.",
         "-- Touches only PerformanceRounds; Performances is never written. Each block asserts the stored time equals the fastest round.",
         "SET XACT_ABORT ON;", "BEGIN TRANSACTION;", ""]
notes = []; total = 0
for mid in sys.argv[3:]:
    perfs = defaultdict(list)
    for l in open(os.path.join(data_dir, mid, 'db.txt')):
        p = l.rstrip('\n').split('|')
        if len(p) >= 7 and p[4] != 'NULL': perfs[(int(p[1]), p[2], p[3])].append((int(p[0]), float(p[4])))
    path = os.path.join(data_dir, mid, 'rounds.txt')
    if not os.path.exists(path): continue
    lines += [f"-- ===== DB meet {mid} =====", ""]
    for raw in open(path):
        raw = raw.strip()
        if not raw: continue
        g, ev, name, rr = raw.split('|'); g = int(g)
        rounds = {RN[x.split(':')[0]]: float(x.split(':')[1]) for x in rr.split(';')}
        best = min(rounds.values()); c = perfs.get((g, ev, name), [])
        if len(c) != 1: notes.append(f"{'AMBIGUOUS' if c else 'NO PERFORMANCE'} meet {mid}: {name} {ev}"); continue
        pid, t = c[0]
        # Hand-timed marks print as hundredths (2:02.8 -> 2:02.08, 13.1 -> 13.01): when that reading is the stored time, use it for that round
        def quirk(v):
            h = round(v * 100) % 100
            return int(v) + (h % 10) / 10 if h % 10 and h // 10 == 0 else None
        for k, v in list(rounds.items()):
            a = quirk(v)
            if a is not None and abs(a - t) < 0.006 and abs(v - t) > 0.006: rounds[k] = round(a, 2)
        best = min(rounds.values())
        if abs(t - best) > 0.06:notes.append(f"TIME MISMATCH meet {mid}: {name} {ev}: fastest round {best} vs DB {t} ({rr})"); continue
        total += 1
        lines.append(f"-- {name} {ev}: " + ', '.join(f"{NAME[k]} {v}" for k, v in sorted(rounds.items())))
        lines.append(f"IF NOT EXISTS (SELECT 1 FROM Performances WHERE Id={pid} AND MeetId={mid} AND ABS(TimeSeconds-{t})<0.06) THROW 50004, 'Time mismatch for performance {pid}', 1;")
        lines.append(f"IF NOT EXISTS (SELECT 1 FROM PerformanceRounds WHERE PerformanceId={pid})")
        lines.append("BEGIN")
        for k, v in sorted(rounds.items()): lines.append(f"    INSERT INTO PerformanceRounds (PerformanceId, Round, TimeSeconds) VALUES ({pid}, {k}, {v});")
        lines.append("END")
        lines.append("")
lines += ["COMMIT TRANSACTION;", "", f"-- {total} round chains"] + [f"-- NOTE: {n}" for n in notes]
open(out, 'w').write('\n'.join(lines) + '\n')
print(f"{total} chains"); [print('NOTE', n) for n in notes]
